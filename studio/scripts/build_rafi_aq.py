# 10 ms energy envelope of the clip's audio
pcm = subprocess.run(['ffmpeg', '-v', 'error', '-i', SRC, '-vn', '-ac', '1', '-ar', '16000', '-f', 's16le', '-'], capture_output=True).stdout
x = np.frombuffer(pcm, np.int16).astype(float) / 32768
hop = 160
db = 20 * np.log10(np.sqrt(np.array([np.mean(x[i*hop:(i+1)*hop]**2) for i in range(len(x)//hop)]) + 1e-12))
sm = np.convolve(db, np.ones(3) / 3, 'same')
dur = len(db) / 100
fr = lambda t: int(round(t * 100))

def cut_in(first, prev):
    lo = max(0.0, (prev - OFF + 0.2) if prev else 0.0, first - OFF - 0.6)
    hi = first - OFF + 0.06
    seg = sm[fr(lo):fr(hi) + 1]
    if len(seg) == 0: return max(0.0, first - OFF - 0.1)
    m = seg.min()
    if m < -50:  # a real pause: cut at its end, right before the first word
        k = max(i for i, v in enumerate(seg) if v <= m + 3)
        return max(0.0, lo + k / 100 - 0.02)
    # words run together: cut at the deepest point between them
    return max(0.0, lo + int(np.argmin(seg)) / 100)

def cut_out(last, nxt):
    lo = last - OFF + 0.18
    hi = min(dur - 0.01, nxt - OFF + 0.04, last - OFF + 1.3)
    seg = sm[fr(lo):fr(hi) + 1]
    m = seg.min()
    for i in range(len(seg) - 5):
        if all(v <= m + 6 for v in seg[i:i + 6]):  # first 60 ms of real quiet after the last word
            return min(hi, lo + i / 100 + 0.05)
    return lo + int(np.argmin(seg)) / 100

